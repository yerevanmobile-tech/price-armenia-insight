export function translate(lang: Lang, key: string): string {
  const entry = dict[key];
  if (!entry) return key;
  return entry[lang === "hy" ? 0 : lang === "ru" ? 1 : 2];
}

export function localizedCategory(lang: Lang, id: string, cats: { id: string; hy: string; ru: string; en: string }[]) {
  const c = cats.find((x) => x.id === id);
  if (!c) return id;
  return lang === "hy" ? c.hy : lang === "ru" ? c.ru : c.en;
}